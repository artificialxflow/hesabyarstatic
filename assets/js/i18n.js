window.HesyI18n = {
  getLang() {
    return localStorage.getItem("hesy-lang") || "fa";
  },
  setLang(lang) {
    localStorage.setItem("hesy-lang", lang);
    this.apply();
  },
  t(key) {
    const pack = window.I18N[this.getLang()] || window.I18N.fa;
    return pack[key] || key;
  },
  apply() {
    const lang = this.getLang();
    const pack = window.I18N[lang];
    document.documentElement.lang = pack.lang;
    document.documentElement.dir = pack.dir;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = pack[el.getAttribute("data-i18n")] || el.textContent;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", pack[el.getAttribute("data-i18n-placeholder")] || "");
    });
    document.dispatchEvent(new CustomEvent("hesy:lang", { detail: { lang } }));
  },
  toggle() {
    this.setLang(this.getLang() === "fa" ? "en" : "fa");
  }
};
